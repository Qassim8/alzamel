export const FEATURED_SERVICES = SERVICES.filter((s) => s.featured);

/** خدمة واحدة عبر الـ slug. */
export function getServiceBySlug(slug) {
  return SERVICES.find((s) => s.slug === slug);
}

/** خدمات مقترحة بجانب خدمة معيّنة (للربط الداخلي). */
export function relatedServices(slug, count = 3) {
  const index = SERVICES.findIndex((s) => s.slug === slug);
  if (index === -1) return SERVICES.slice(0, count);
  return Array.from(
    { length: count },
    (_, i) => SERVICES[(index + i + 1) % SERVICES.length],
  );
}
